// witness capture plugin for OpenCode v2 (2.2.7 or newer; the contract below was observed on
// 2.2.7 and 2.3.0).
//
// This file is the one source of both copies. `witness wire opencode` writes it to
// <config>/plugins/witness.js with a `globalThis.WITNESS_SHIM = "<target>"` line prepended
// (plugin.go). npm/opencode/witness.js is npm_prelude.js + this file, regenerated by
// `WITNESS_WRITE_NPM_PLUGIN=1 go test ./internal/platform/opencode/plugin/` and checked by that
// test. The prelude defines WITNESS_NPM, so its presence is what tells the npm copy apart.
//
// v2 loads only `export default { id, setup }`. setup runs once per opened directory (Location)
// and again on every hot reload, and every instance sees every event on one global bus, with the
// same event id in each. So all state lives on globalThis and each event is handled once, by id.
const NPM = typeof WITNESS_NPM === "object" ? WITNESS_NPM : null
const WITNESS_BIN = NPM ? NPM.bin : globalThis.WITNESS_SHIM || process.env.WITNESS_BIN || "witness"
const QUIET_PERIOD_MS = 5 * 60 * 1000
const TURN_END = ["session.execution.succeeded", "session.execution.failed", "session.execution.interrupted"]

// Shared by every Location instance and by both copies when OpenCode loads the npm package and a
// wired file, and it survives hot reload. A new state shape needs a new key: a reloaded module
// would otherwise find the old object without the new fields.
const S = (globalThis.__witnessCaptureV2 ??= {
  synced: false, // the startup import ran (once per OpenCode process)
  fetched: false, // npm: `witness model fetch` ran (once per OpenCode process)
  seen: new Set(), // event ids already handled by some instance
  // ponytail: an entry leaks if the server dies mid-turn; that only delays the quiet kick until
  // OpenCode restarts. Clear it on location.shutdown if that ever matters.
  running: new Set(), // sessions between execution.started and a turn end
  pending: new Set(), // sessions waiting for the next import
  active: null, // the running per-session import, so imports run one at a time
  quiet: null, // the quiet-period timer
})

function spawnWitness(args) {
  if (process.env.WITNESS_WORKER === "1") return
  try {
    // WITNESS_OPENCODE_BIN: the Windows desktop's CLI (opencode-cli.exe) is never on PATH, so
    // witness's OpenCode resolver takes the binary that is running this plugin.
    const env = { ...process.env, WITNESS_OPENCODE_BIN: process.execPath }
    // npm: the binary sits in a per-platform package and cannot find this package's prompts or
    // the model dir, and an npm user never ran `wire`, so the runner defaults to OpenCode. Each
    // is a fallback; a value the user set wins.
    if (NPM) for (const [k, v] of Object.entries(NPM.env)) env[k] ||= v
    const proc = Bun.spawn([WITNESS_BIN, ...args], { stdin: "ignore", stdout: "ignore", stderr: "ignore", env })
    proc.unref?.()
    return proc
  } catch {
    // A plugin must never break an OpenCode session.
  }
}

// The turn-end import is L0-only (--no-kick): distillation starts from the quiet-period kick,
// not after every turn.
function drain() {
  if (S.active || S.pending.size === 0) return
  const args = ["import", "--agent", "opencode", "--quiet", "--no-kick"]
  for (const id of S.pending) args.push("--session", id)
  S.pending.clear()
  const proc = spawnWitness(args)
  if (!proc) return
  S.active = proc
  Promise.resolve(proc.exited)
    .catch(() => {})
    .finally(() => {
      S.active = null
      drain()
    })
}

// worker-kick, not `worker-run --auto`: the kick is the gate that clears a latched
// worker_stop_requested and applies the auto-start rules.
function scheduleQuiet() {
  if (S.quiet) clearTimeout(S.quiet)
  S.quiet = setTimeout(() => {
    S.quiet = null
    spawnWitness(["worker-kick"])
  }, QUIET_PERIOD_MS)
  S.quiet.unref?.()
}

export default {
  id: "witness",
  async setup(ctx) {
    if (!WITNESS_BIN || process.env.WITNESS_WORKER === "1") return
    if (NPM) {
      // Every setup registers; that is idempotent, since an existing entry (the user's, or one
      // another instance set) is left alone. WITNESS_NPM_PACKAGE=1 makes `witness mcp` start
      // without the model, as `npx` already does.
      try {
        await ctx.mcp.transform((ed) => {
          if (!ed.get("witness")) {
            ed.set("witness", {
              type: "local",
              command: [WITNESS_BIN, "mcp"],
              environment: { ...NPM.env, WITNESS_NPM_PACKAGE: "1", WITNESS_OPENCODE_BIN: process.execPath },
            })
          }
        })
      } catch {}
      if (!S.fetched) {
        // The npm package ships without the ~470 MB model. Files already right are only hashed.
        S.fetched = true
        if (process.env.WITNESS_SKIP_MODEL_DOWNLOAD !== "1") spawnWitness(["model", "fetch"])
      }
    }
    if (!S.synced) {
      // Once per server process, not per Location and not per hot reload.
      S.synced = true
      spawnWitness(["import", "--agent", "opencode", "--quiet", "--no-kick"])
    }
    const ac = new AbortController()
    ;(async () => {
      for await (const e of ctx.event.subscribe({ types: ["session.execution.started", ...TURN_END], signal: ac.signal })) {
        if (S.seen.has(e.id)) continue
        S.seen.add(e.id)
        if (S.seen.size > 512) S.seen.delete(S.seen.values().next().value)
        const id = e.data?.sessionID
        if (!id) continue
        if (e.type === "session.execution.started") {
          // No quiet-period kick while any session runs: on 2.3.0 a parent's turn ends while its
          // background subagent still works, then ends again after the child reports.
          S.running.add(id)
          if (S.quiet) clearTimeout(S.quiet)
          S.quiet = null
          continue
        }
        // Every turn end imports, the parent's partial and final ones included; the importer is
        // incremental, and the event-id dedupe above already drops the other instances' copies.
        S.running.delete(id)
        S.pending.add(id)
        drain()
        if (S.running.size === 0) scheduleQuiet()
      }
    })().catch(() => {})
    // No `worker stop` here: cleanup gets ~5 s before `opencode service stop` (or a version
    // replace) SIGKILLs the server, it runs on every hot reload and once per instance, and
    // `worker stop --auto-only` latches worker_stop_requested, so auto workers would stay stopped
    // after every `wire` or upgrade. It must never throw: on 2.2.7 that can stall a reload.
    return () => {
      try {
        ac.abort()
      } catch {}
    }
  },
}
